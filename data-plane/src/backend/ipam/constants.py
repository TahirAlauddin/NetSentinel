# Regex pattern for validating IPv4 and IPv6 CIDR notation
CIDR_REGEX_PATTERN = r"""^(
                (
                    (25[0-5]|2[0-4][0-9]|1[0-9]{2}|[1-9]?[0-9])\.
                    (25[0-5]|2[0-4][0-9]|1[0-9]{2}|[1-9]?[0-9])\.
                    (25[0-5]|2[0-4][0-9]|1[0-9]{2}|[1-9]?[0-9])\.
                    (25[0-5]|2[0-4][0-9]|1[0-9]{2}|[1-9]?[0-9])
                )
                \/(3[0-2]|[12]?[0-9])
                |
                (
                    ([A-Fa-f0-9]{1,4}:){7}[A-Fa-f0-9]{1,4}
                    |
                    ([A-Fa-f0-9]{1,4}:){1,7}:
                    |
                    :(:[A-Fa-f0-9]{1,4}){1,7}
                )
                \/(12[0-8]|1[01][0-9]|[1-9]?[0-9])
                )$
                """
